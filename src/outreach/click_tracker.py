"""Preview Link Click Tracker & Fast-Follow Dispatcher.

Captures when a prospect clicks their personalized Next.js preview URL, logs the
engagement in PostgreSQL, and — per leads-improve-plan.md Section 3 — closes the
loop on that buying-intent signal instead of letting it dead-end at a Telegram
ping: the first click queues the already-generated WhatsApp follow-up (ready to
copy-send within minutes) and a repeat click escalates the lead to HOT_ENGAGED so
it visibly jumps the admin queue instead of blending into the general VIEWED
bucket."""

from datetime import datetime
from typing import Dict, Any, Optional
from sqlalchemy.future import select

from src.storage.db_session import AsyncSessionLocal
from src.storage.models import OutreachLeadModel, BusinessModel, OutreachLogModel, ClientSiteModel
from src.storage.audit_logger import audit_logger
from src.utils.logger import logger

# A prospect who has already converted or opted out shouldn't be re-escalated by
# further clicks (e.g. them re-reading the site after signing, or a stale link).
_TERMINAL_STATUSES = ("CONVERTED", "OPTED_OUT")


class ClickTracker:

    async def record_preview_click(self, slug: str, ip_address: Optional[str] = None, user_agent: Optional[str] = None) -> Dict[str, Any]:
        """Record prospect preview site click, queue a fast-follow on first click,
        escalate to HOT_ENGAGED on repeat clicks, and notify Telegram."""
        business_name = slug.replace("-", " ").title()
        whatsapp_draft: Optional[str] = None
        phone: Optional[str] = None
        is_hot = False
        fastfollow_queued = False

        async with AsyncSessionLocal() as session:
            async with session.begin():
                site = (await session.execute(select(ClientSiteModel).where(ClientSiteModel.slug == slug))).scalars().first()
                business_id = site.business_id if site else None

                if business_id:
                    business = (await session.execute(select(BusinessModel).where(BusinessModel.id == business_id))).scalars().first()
                    if business:
                        business_name = business.name
                        phone = business.phone

                    lead = (await session.execute(select(OutreachLeadModel).where(OutreachLeadModel.business_id == business_id))).scalars().first()
                    if not lead:
                        lead = OutreachLeadModel(business_id=business_id, outreach_status="VIEWED")
                        session.add(lead)
                        await session.flush()

                    lead.preview_clicked = True
                    lead.click_count = (lead.click_count or 0) + 1
                    lead.last_clicked_at = datetime.utcnow()
                    whatsapp_draft = lead.whatsapp_draft

                    if lead.outreach_status not in _TERMINAL_STATUSES:
                        if lead.click_count >= 2:
                            # Repeat visit after being contacted is a stronger buying
                            # signal than the raw modernization score — surface it.
                            lead.outreach_status = "HOT_ENGAGED"
                            is_hot = True
                        elif lead.outreach_status in ("NEW", "EMAIL_SENT"):
                            lead.outreach_status = "VIEWED"

                    # Add the standard click log entry
                    session.add(OutreachLogModel(
                        outreach_lead_id=lead.id,
                        channel="EMAIL",
                        action="LINK_CLICKED",
                        sent_subject=f"Prospect opened preview site: {slug}",
                        sent_body=f"IP: {ip_address or 'Unknown'}, UserAgent: {user_agent or 'Unknown'}"
                    ))

                    # Fast-follow: on the FIRST click only, queue the WhatsApp draft
                    # (already generated by the outreach studio, if any) so the admin
                    # can send it within minutes rather than whenever they next check
                    # Telegram. Logged once per lead, not on every subsequent click.
                    if lead.click_count == 1:
                        fastfollow_queued = True
                        session.add(OutreachLogModel(
                            outreach_lead_id=lead.id,
                            channel="WHATSAPP",
                            action="FASTFOLLOW_QUEUED",
                            sent_body=whatsapp_draft or (
                                "(No WhatsApp draft generated yet — open the Outreach "
                                "Studio for this lead to generate one before following up.)"
                            )
                        ))

        # Audit log event
        audit_logger.log_event(
            "SUCCESS",
            "OUTREACH",
            f"🔥 Prospect '{business_name}' is actively viewing their preview website at /sites/{slug}!"
            + (" This is a REPEAT visit — escalated to HOT_ENGAGED." if is_hot else ""),
            business_name=business_name
        )
        if fastfollow_queued:
            audit_logger.log_event(
                "INFO",
                "OUTREACH",
                f"📲 Fast-follow WhatsApp message queued for '{business_name}' following their first preview click.",
                business_name=business_name
            )

        # Dispatch Telegram push alert, enriched with the ready-to-send fast-follow
        # message and a direct wa.me link when a phone number is known.
        try:
            from src.notifications.telegram_bot import telegram_bot
            await telegram_bot.send_click_alert(
                business_name, slug,
                whatsapp_draft=whatsapp_draft if fastfollow_queued else None,
                phone=phone,
                is_hot=is_hot,
            )
        except Exception as e:
            logger.warning(f"Telegram click alert failed: {e}")

        return {
            "status": "recorded",
            "slug": slug,
            "business_name": business_name,
            "hot_engaged": is_hot,
            "fastfollow_queued": fastfollow_queued,
            "timestamp": datetime.utcnow().isoformat() + "Z"
        }

click_tracker = ClickTracker()
